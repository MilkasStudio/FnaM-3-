export function getTranslation(lang: Language, key: keyof typeof TRANSLATIONS['en']): string {
  const translationsForLang = TRANSLATIONS[lang] || TRANSLATIONS['en'];
  const text = (translationsForLang as any)[key] || (TRANSLATIONS['en'] as any)[key] || '';
  return text;
}

export function getFormattedTranslation(
  lang: Language,
  key: keyof typeof TRANSLATIONS['en'],
  replaceParams: Record<string, string | number>
): string {
  let text = getTranslation(lang, key);
  Object.keys(replaceParams).forEach((paramKey) => {
    text = text.replace(`{${paramKey}}`, String(replaceParams[paramKey]));
  });
  return text;
}
